# -*- coding: utf-8 -*-
"""Крок 3. Збирає з index1.json людський покажчик витягнутого тексту."""
import json, io, os, collections
B = r'G:\ostriv-znan\програма-1-клас\робоче'
idx = json.load(io.open(os.path.join(B, 'index1.json'), encoding='utf-8'))
L = []
a = L.append
a('# Покажчик витягнутого тексту PDF 1 класу\n')
a('Перезбирається двома ідемпотентними кроками: `step1_extract.py` (сире витягання')
a('у `txt_raw\\`) -> `step2_fixenc.py` (виправлення кодування у `txt\\`).')
a('Назва файлу тексту — перші 12 знаків sha1 самого PDF, тому дублі збігаються.\n')
a('| Стан | Файлів |')
a('|---|---:|')
for k, v in collections.Counter(r['status'] for r in idx).most_common():
    a('| %s | %d |' % (k, v))
a('| **усього записів** | **%d** |\n' % len(idx))
a('Стани: `raw` — текстовий шар є і читається; `dup` — байт-у-байт копія іншого')
a('файлу; `scan` — текстового шару немає, потрібен OCR; `err` — не відкрився.\n')
a('## По предметах\n')
a('| Предмет | Файлів | Унікальних | Дублів | Сканів | Виправлено кодування |')
a('|---|---:|---:|---:|---:|---:|')
for s in sorted(set(r['subject'] for r in idx)):
    rs = [r for r in idx if r['subject'] == s]
    a('| %s | %d | %d | %d | %d | %d |' % (
        s, len(rs),
        sum(1 for r in rs if r['status'] == 'raw'),
        sum(1 for r in rs if r['status'] == 'dup'),
        sum(1 for r in rs if r['status'] == 'scan'),
        sum(1 for r in rs if r.get('enc') == 'fixed')))
a('')
a('## Потребує OCR (агент `G:\\LOCAL AI AGENTS\\10_OCR`)\n')
sc = [r for r in idx if r['status'] == 'scan']
if not sc:
    a('немає\n')
else:
    for r in sc:
        a('- `%s` — %s стор., текстового шару майже немає (%s знаків)'
          % (r['path'], r.get('pages'), r.get('chars')))
    a('')
a('## Файли, де виправлено шрифтове кодування кирилиці\n')
a('Пастка брифа №2 знята **без OCR**. Кирилиця в цих PDF записана cp1251, а')
a('читається як cp1252 — звідси «îñâіòà» замість «освіта». Наївне перекодування')
a('тут не годиться: воно так само перетворює на кирилицю справжню латиницю з')
a('діакритикою (нім. «Ää» -> «Фд», угор. «á», ісп. «ñ»), а в збірці є підручники')
a('німецької, іспанської, французької, угорської та методика угорської мови.')
a('Тому рішення ухвалюється **по файлу** й перевіряється словником українських')
a('слів, зібраним із тих файлів, де текст і так чистий (`_словник.txt`).')
a('Розділення вийшло чистим: іномовні підручники дають частку влучань 0,00–0,01')
a('і лишаються незмінними, україномовні з ламаним шрифтом — 0,53–0,94.\n')
a('| Влучань у словник | Токенів-кандидатів | Файл |')
a('|---:|---:|---|')
for r in sorted([x for x in idx if x.get('enc') == 'fixed'], key=lambda x: -x['enc_cands']):
    a('| %.2f | %d | %s |' % (r['enc_score'], r['enc_cands'], r['path']))
a('')
io.open(os.path.join(B, '_покажчик.md'), 'w', encoding='utf-8').write('\n'.join(L))
print('ok', len(idx))
