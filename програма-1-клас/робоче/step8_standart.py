# -*- coding: utf-8 -*-
"""Крок 8. Витягає з Держстандарту обов'язкові результати на кінець 1 циклу.

У стандарті результати позначено кодом у квадратних дужках у КІНЦІ рядка:
«...доречно реагує [2 МОВ 1.1]». Префікс 2 = на кінець 2 класу (1 цикл),
4 = на кінець 4 класу. Нас цікавить лише префікс 2.
Савченко посилається на ті самі пункти як [1 МОВ 1.1], Шиян як
[2 МОВ 1-1.1-1] — спільне в них пара «галузь + номер групи» (МОВ 1.1),
і саме за нею треба зшивати програму зі стандартом.

Ідемпотентний: пише `_результати_1_цикл.md` і `_результати.json`.
"""
import io, os, re, json, collections

B = r'G:\ostriv-znan\програма-1-клас\робоче'
SRC = os.path.join(B, '_\u0414\u0435\u0440\u0436\u0441\u0442\u0430\u043d\u0434\u0430\u0440\u0442.txt')
RE = re.compile(r'(.{10,600}?)\[\s*2\s+([\u0410-\u042f\u0406\u0407\u0404\u0490]{3})\s+(\d+\.\d+)\s*\]')
NAMES = {
    '\u041c\u041e\u0412': '\u041c\u043e\u0432\u043d\u043e-\u043b\u0456\u0442\u0435\u0440\u0430\u0442\u0443\u0440\u043d\u0430',
    '\u0406\u041d\u041e': '\u0406\u043d\u0448\u043e\u043c\u043e\u0432\u043d\u0430',
    '\u041c\u0410\u041e': '\u041c\u0430\u0442\u0435\u043c\u0430\u0442\u0438\u0447\u043d\u0430',
    '\u041f\u0420\u041e': '\u041f\u0440\u0438\u0440\u043e\u0434\u043d\u0438\u0447\u0430',
    '\u0422\u0415\u041e': '\u0422\u0435\u0445\u043d\u043e\u043b\u043e\u0433\u0456\u0447\u043d\u0430',
    '\u0406\u0424\u041e': '\u0406\u043d\u0444\u043e\u0440\u043c\u0430\u0442\u0438\u0447\u043d\u0430',
    '\u0421\u0417\u041e': '\u0421\u043e\u0446\u0456\u0430\u043b\u044c\u043d\u0430 \u0456 \u0437\u0434\u043e\u0440\u043e\u0432\u2019\u044f\u0437\u0431\u0435\u0440\u0435\u0436\u0443\u0432\u0430\u043b\u044c\u043d\u0430',
    '\u0413\u0406\u041e': '\u0413\u0440\u043e\u043c\u0430\u0434\u044f\u043d\u0441\u044c\u043a\u0430 \u0442\u0430 \u0456\u0441\u0442\u043e\u0440\u0438\u0447\u043d\u0430',
    '\u041c\u0418\u041e': '\u041c\u0438\u0441\u0442\u0435\u0446\u044c\u043a\u0430',
    '\u0424\u0406\u041e': '\u0424\u0456\u0437\u043a\u0443\u043b\u044c\u0442\u0443\u0440\u043d\u0430',
}
text = io.open(SRC, encoding='utf-8').read()
items = {}
for m in RE.finditer(text):
    body = re.sub(r'\s+', ' ', m.group(1)).strip()
    body = body.split('\n')[-1].strip()
    # відрізаємо хвіст попереднього пункту
    body = re.sub(r'^.*\]\s*', '', body).strip()
    key = (m.group(2), m.group(3))
    if key not in items or len(body) > len(items[key]):
        items[key] = body
L = []
a = L.append
a('# Обов\u2019язкові результати навчання на кінець 1 циклу (1\u20132 клас)\n')
a('Джерело: Державний стандарт початкової освіти (постанова КМУ № 87 від')
a('21.02.2018, чинна редакція) — файл лежить у збірці лише як HTML.')
a('Префікс коду `2` означає «на кінець 2 класу». Савченко посилається на ті')
a('самі пункти як `[1 МОВ 1.1]`, Шиян як `[2 МОВ 1-1.1-1]`; спільна частина —')
a('**галузь + номер групи** (`МОВ 1.1`), і зшивати треба за нею.\n')
groups = collections.defaultdict(list)
for (g, n), body in items.items():
    groups[g].append((tuple(int(x) for x in n.split('.')), n, body))
order = ['\u041c\u041e\u0412', '\u0406\u041d\u041e', '\u041c\u0410\u041e', '\u041f\u0420\u041e', '\u0422\u0415\u041e',
         '\u0406\u0424\u041e', '\u0421\u0417\u041e', '\u0413\u0406\u041e', '\u041c\u0418\u041e', '\u0424\u0406\u041e']
total = 0
for g in order + [x for x in sorted(groups) if x not in order]:
    if g not in groups:
        continue
    a('## %s — `%s`\n' % (NAMES.get(g, g), g))
    a('| Код | Обов\u2019язковий результат на кінець 2 класу |')
    a('|---|---|')
    for _, n, body in sorted(groups[g]):
        a('| `%s %s` | %s |' % (g, n, body[:400]))
        total += 1
    a('')
io.open(os.path.join(B, '_\u0440\u0435\u0437\u0443\u043b\u044c\u0442\u0430\u0442\u0438_1_\u0446\u0438\u043a\u043b.md'),
        'w', encoding='utf-8').write('\n'.join(L))
io.open(os.path.join(B, '_\u0440\u0435\u0437\u0443\u043b\u044c\u0442\u0430\u0442\u0438.json'), 'w', encoding='utf-8').write(
    json.dumps({'%s %s' % k: v for k, v in items.items()}, ensure_ascii=False, indent=1))
print('результатів 1 циклу:', total, 'галузей:', len(groups))
