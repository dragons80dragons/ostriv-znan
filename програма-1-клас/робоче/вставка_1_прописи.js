const ALL_LOW = LET_GROUPS.flat();
const ALL_UP = ALL_LOW.filter(c => c !== 'ь').map(c => c.toUpperCase());
// Ідентифікатор кліпа — за латинською назвою літери, а НЕ за номером у
// списку. Інакше дев'ять уже записаних підказок (t_a, t_m, t_en, t_el,
// t_es, t_ka, t_o, t_u, t_y і великі до них) осиротіли б, і гра читала б
// їх синтезатором, маючи готовий запис поруч.
const LET_ID = {
  'а':'a','о':'o','у':'u','и':'y','і':'i','е':'e','є':'ye','ю':'yu','я':'ya',
  'ї':'yi','й':'j','ь':'soft','м':'m','н':'en','л':'el','с':'es','к':'ka',
  'б':'be','в':'ve','г':'he','ґ':'ge','д':'de','ж':'zhe','з':'ze','п':'pe',
  'р':'er','т':'te','ф':'ef','х':'ha','ц':'tse','ч':'che','ш':'sha','щ':'shcha',
};
const letVo = c => 't_' + LET_ID[c];
const letVoUp = c => 't_v_' + LET_ID[c];

// Прописи. Рівень 1 — малі літери перших груп, рівень 2 — малі решти груп,
// рівень 3 — великі. Цифри домішуються на кожному рівні, бо їх теж 10,
// і без них дитина дійде до «8» аж у травні.
function traceTasks(v){
  const t = [];
  const low = v === 1 ? LET_GROUPS.slice(0, 3).flat() : LET_GROUPS.slice(3).flat();
  if (v === 3){
    for (const ch of pick(ALL_UP, 3))
      t.push({kind:'trace', glyph:ch, hard:true, prompt:'Обведи пальцем велику букву ' + ch,
        speak:[[letVoUp(ch.toLowerCase()), 'Обведи пальцем велику букву ' + LET_NAME[ch.toLowerCase()]]]});
  } else {
    for (const ch of pick(low.filter(c => PEN[c]), 3))
      t.push({kind:'trace', glyph:ch, hard:false, prompt:'Обведи пальцем букву ' + ch,
        speak:[[letVo(ch), 'Обведи пальцем букву ' + LET_NAME[ch]]]});
  }
  const digits = v === 1 ? pick([1,2,3,4,5], 2) : v === 2 ? pick([0,5,6,7], 2) : pick([6,7,8,9,0], 2);
  for (const k of digits)
    t.push({kind:'trace', glyph:String(k), hard:v===3, prompt:'Обведи пальцем цифру '+k,
      speak:[['t_d'+k, 'Обведи пальцем цифру '+NUM[k]]]});
  return t;
}
